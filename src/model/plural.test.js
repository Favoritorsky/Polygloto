import { expect, it } from 'vitest';
import { plural } from './plural.js';

const forms = ['курс', 'курса', 'курсов'];

it('склоняет по числу, включая 11–14', () => {
  expect([0, 1, 2, 5, 11, 12, 14, 21, 22, 25, 101, 111].map((n) => plural(n, forms))).toEqual([
    'курсов', 'курс', 'курса', 'курсов', 'курсов', 'курсов', 'курсов', 'курс', 'курса', 'курсов', 'курс', 'курсов',
  ]);
});
